const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('rgb', {
  connect: (host, port) => ipcRenderer.invoke('openrgb:connect', host, port),
  refresh: () => ipcRenderer.invoke('openrgb:refresh'),
  onDevicesUpdated: (cb) => ipcRenderer.on('devices-updated', (_e, d) => cb(d)),
  onConnLost: (cb) => ipcRenderer.on('conn-lost', (_e, msg) => cb(msg)),
  onConnRestored: (cb) => ipcRenderer.on('conn-restored', (_e, d) => cb(d)),
  onRingSynced: (cb) => ipcRenderer.on('ring-synced', (_e, mode) => cb(mode)),
  onRingSyncFailed: (cb) => ipcRenderer.on('ring-sync-failed', (_e, msg) => cb(msg)),
  listEffects: () => ipcRenderer.invoke('effects:list'),
  setDeviceState: (id, partial) => ipcRenderer.invoke('device:setState', id, partial),
  resizeZone: (id, zoneId, size) => ipcRenderer.invoke('device:resizeZone', id, zoneId, size),
  autoSetZones: (mode) => ipcRenderer.invoke('zones:autoSet', mode),
  setZoneFormat: (id, zoneId, format, physical) => ipcRenderer.invoke('zone:setFormat', id, zoneId, format, physical),
  applyAll: (partial) => ipcRenderer.invoke('device:applyAll', partial),

  sensors: () => ipcRenderer.invoke('sensors:get'),
  hw: () => ipcRenderer.invoke('hw:get'),
  onHwChanged: (cb) => ipcRenderer.on('hw-changed', (_e, h) => cb(h)),
  openPawnio: () => ipcRenderer.invoke('app:openPawnio'),
  periph: {
    scan: () => ipcRenderer.invoke('periph:scan'),
    saveMouse: (id, cfg) => ipcRenderer.invoke('periph:saveMouse', id, cfg),
    restoreMouse: (id) => ipcRenderer.invoke('periph:restoreMouse', id),
    integrations: () => ipcRenderer.invoke('periph:integrations'),
    kbScan: () => ipcRenderer.invoke('periph:kbScan'),
    kbSave: (want) => ipcRenderer.invoke('periph:kbSave', want),
    kbRestore: () => ipcRenderer.invoke('periph:kbRestore'),
    pickApp: () => ipcRenderer.invoke('periph:pickApp'),
    runAction: (act) => ipcRenderer.invoke('periph:runAction', act),
  },
  appInfo: () => ipcRenderer.invoke('app:info'),
  setTitleBar: (bg) => ipcRenderer.invoke('app:titlebar', bg),
  openLogs: () => ipcRenderer.invoke('app:openLogs'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (partial) => ipcRenderer.invoke('settings:set', partial),
  giphyDownload: (url, id) => ipcRenderer.invoke('giphy:download', url, id),

  loadProfiles: () => ipcRenderer.invoke('profiles:load'),
  saveProfile: (name) => ipcRenderer.invoke('profiles:save', name),
  applyProfile: (name) => ipcRenderer.invoke('profiles:apply', name),

  lcd: {
    init: () => ipcRenderer.invoke('lcd:init'),
    status: () => ipcRenderer.invoke('lcd:status'),
    liquid: () => ipcRenderer.invoke('lcd:liquid'),
    brightness: (pct) => ipcRenderer.invoke('lcd:brightness', pct),
    orientation: (deg) => ipcRenderer.invoke('lcd:orientation', deg),
    pickImage: () => ipcRenderer.invoke('lcd:pickImage'),
    sendGif: (path) => ipcRenderer.invoke('lcd:gif', path),
    sendImage: (path) => ipcRenderer.invoke('lcd:image', path),
    pushFrame: (dataUrl) => ipcRenderer.invoke('lcd:pushFrame', dataUrl),
    ring: (mode, colors, speed) => ipcRenderer.invoke('lcd:ring', mode, colors, speed),
    info: () => ipcRenderer.invoke('lcd:info'),
  },
});
